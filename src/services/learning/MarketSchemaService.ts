/**
 * MarketSchemaService — the MARKET_SCHEMA half of the indexed memory
 * topology (Meta-RAM: MARKET_SCHEMA + REGISTRY + detail pointers).
 *
 * WHY THIS EXISTS. The notebook's LOAD surface already reads a REGISTRY
 * (`rules/recurring-mistakes.md` — symptom → pointer) and a per-coin diary
 * recency window. What it did not carry was the MARKET's own index facts:
 * the tick/lot units an entry must respect, the funding clock, the session
 * overlaps and the regime conventions the app itself classifies by. A seat
 * that never sees them guesses precision, misreads a funding squeeze as
 * structure, and calls a range tape a trend — entry-knowable mistakes the
 * journal then records as lessons. This file is the crisp, symbol-scoped
 * index that closes that gap: one compact file per coin, harness-maintained,
 * injected bounded by `MemoryRetrievalService › marketSchemaBlock`, with the
 * verbose detail staying behind pointers (the coin's diary, get_trade_log).
 *
 * GROUNDING RULES.
 *  - Units come from exchangeInfo (`MarketDataService › fetchSymbolUnits`).
 *    Unreachable ⇒ the line says "unverified", never a made-up number.
 *  - The funding schedule is MEASURED from the settlement history's spacing
 *    when it is reachable; the 8h USDT-perp convention is the labelled
 *    fallback, not a silent assumption.
 *  - Sessions and regime thresholds are the app's OWN conventions
 *    (`regimeCore › regimeRead` defaults) — stating them is what lets a seat
 *    read "compressed" the same way the chart does.
 *  - Learned traps are derived from REAL journal rows only: a `simulated`
 *    paper fill never writes a real-market trap (Phase 6 isolation).
 *
 * The folder is harness-owned: `writeModelNote` refuses it, and the whole
 * folder is regenerated by the OFFLOAD passes (memoryOffload.ts), the same
 * discipline `rules/recurring-mistakes.md` lives under.
 */

import { LoggedTrade, TradeOutcome } from '../../types';
import { baseOf } from '../../utils/symbol';
import {
    findFolderByName,
    getMemoryFiles,
    upsertHarnessFileUnlocked,
    withNotebookWriteLock,
} from './MemoryFilesService';
import { fetchFundingRateHistory, fetchMarkIndex, fetchSymbolUnits } from '../analysis/MarketDataService';

export const MARKET_SCHEMA_FOLDER = 'market-schema';

/** The whole file's ceiling — an INDEX, not a prose wall. The builder keeps
 *  the convention lines whole and drops the oldest trap lines first. */
export const MARKET_SCHEMA_FILE_MAX_CHARS = 900;
/** The LOAD injection ceiling (MemoryRetrievalService). Smaller than the
 *  file: the slice shares one budget with the skill, rules and diary. */
export const MARKET_SCHEMA_MAX_CHARS = 420;
/** A trap needs this many real losses of its kind before it is written —
 *  the same thin-sample floor the harness-optimization pass uses. */
export const SCHEMA_TRAP_MIN_COUNT = 2;
/** At most this many trap lines per coin — the index stays scannable. */
export const SCHEMA_TRAP_MAX_LINES = 2;

/** The session-overlap convention, UTC. One line, the same for every coin —
 *  it is the clock the trader's sessions run on, not a per-symbol fact. */
export const SESSION_OVERLAP_LINE =
    'sessions: Asia 00–08 · London 07–16 · NY 13–22 UTC; 13–16 overlap = peak liquidity';

/** The regime convention — `regimeCore › regimeRead`'s declared defaults,
 *  stated so a seat reads the chart's words the same way the chart does. */
export const REGIME_CONVENTION_LINE =
    'regime: ADX14 ≥25 + ER≥0.35 trend · ≤20 range · else neutral; vol ATR14/BBW pct ≥80 high · ≤20 compressed';

export interface SchemaTrap {
    /** The symptom, one line, entry-knowable. */
    line: string;
    /** How many real losses back it. */
    count: number;
}

export interface MarketSchemaFacts {
    tickSize?: number | null;
    stepSize?: number | null;
    baseAsset?: string;
    quoteAsset?: string;
    /** Measured settlement spacing, hours. Absent ⇒ the labelled convention. */
    fundingIntervalHours?: number | null;
    fundingMeasured?: boolean;
    /** Next settlement, "HH:MM UTC". */
    nextFundingUtc?: string | null;
    /** Learned traps. `undefined` ⇒ preserve the file's existing trap lines
     *  (a units-only refresh must not erase what OFFLOAD learned). */
    traps?: SchemaTrap[];
}

const fmtStep = (v: number): string => {
    // Tick steps are powers of ten (0.1, 0.01, 0.001…) — print them without
    // float noise, never in scientific notation a seat must decode.
    const s = v.toFixed(10).replace(/0+$/, '').replace(/\.$/, '');
    return s.includes('.') ? s : `${s}`;
};

/** The pointer every trap line ends with — the detail's address. */
const trapPointer = (coin: string): string => `trader-diary/${coin}.md`;

/**
 * Pure content builder (exported for the contract check). Compact by
 * construction: one line per fact, conventions always whole, trap lines
 * dropped oldest-first when the file would pass its ceiling.
 */
export const buildMarketSchemaContent = (coin: string, facts: MarketSchemaFacts): string => {
    const cleanCoin = (coin || '').replace(/[^A-Za-z0-9_-]/g, '') || 'GENERAL';
    const head = [
        `# ${cleanCoin} — market schema (auto-maintained)`,
        `> Index for LOAD: units, funding, sessions, regime conventions. Detail behind pointers: ${trapPointer(cleanCoin)}, get_trade_log ${cleanCoin}.`,
    ];
    const units = (typeof facts.tickSize === 'number' && facts.tickSize > 0)
        ? `units: tick ${fmtStep(facts.tickSize)} ${facts.quoteAsset ?? 'USDT'}${typeof facts.stepSize === 'number' && facts.stepSize > 0 ? ` · step ${fmtStep(facts.stepSize)} ${facts.baseAsset ?? cleanCoin}` : ''}`
        : 'units: unverified — exchangeInfo unreachable; confirm tick/step before sizing';
    const interval = typeof facts.fundingIntervalHours === 'number' && facts.fundingIntervalHours > 0
        ? `${fmtStep(facts.fundingIntervalHours)}h${facts.fundingMeasured ? ' (measured)' : ' (convention)'}`
        : '8h (convention, unmeasured)';
    const funding = `funding: every ${interval}${facts.nextFundingUtc ? ` · next ${facts.nextFundingUtc}` : ''}`;
    const trapLines = (facts.traps ?? [])
        .slice(0, SCHEMA_TRAP_MAX_LINES)
        .map(t => `trap: ${t.line} ×${t.count} → detail: ${trapPointer(cleanCoin)}`);
    const body = [`- ${units}`, `- ${funding}`, `- ${SESSION_OVERLAP_LINE}`, `- ${REGIME_CONVENTION_LINE}`, ...trapLines.map(l => `- ${l}`)];
    // The ceiling drops TRAP lines first (newest kept), never the conventions.
    let text = [...head, ...body].join('\n');
    while (text.length > MARKET_SCHEMA_FILE_MAX_CHARS && trapLines.length > 0) {
        trapLines.shift();
        text = [...head, ...body.slice(0, 4), ...trapLines.map(l => `- ${l}`)].join('\n');
    }
    return text;
};

/** Read the coin's schema file — the same exact/pair/prefix matching the
 *  diary reader uses, so a bare "BTC" query finds "BTCUSDT.md". Sync: the
 *  retrieval layer reads the cache every writer maintains. */
export const readMarketSchema = (coin: string): string => {
    const safe = (coin || '').replace(/[^A-Za-z0-9_-]/g, '');
    if (!safe) return '';
    const folder = findFolderByName(MARKET_SCHEMA_FOLDER);
    if (!folder) return '';
    const inFolder = getMemoryFiles().files.filter(f => f.folderId === folder.id);
    const strip = (name: string): string => name.replace(/\.md$/i, '').replace(/[^A-Za-z0-9_-]/g, '');
    const file = inFolder.find(f => strip(f.name) === safe)
        ?? inFolder.find(f => strip(f.name) === `${safe}USDT`)
        ?? inFolder.find(f => strip(f.name).startsWith(safe));
    return file?.enabled === false ? '' : (file?.content ?? '');
};

/** The existing trap lines, parsed back out of the file so a units-only
 *  refresh preserves what OFFLOAD learned. */
const existingTraps = (coin: string): SchemaTrap[] => {
    const content = readMarketSchema(coin);
    if (!content) return [];
    const out: SchemaTrap[] = [];
    for (const line of content.split('\n')) {
        const m = line.match(/^- trap: (.+) ×(\d+) → detail:/);
        if (m) out.push({ line: m[1], count: Number(m[2]) });
    }
    return out;
};

/** Write the coin's schema index. Caller holds the notebook write lock (or
 *  uses the serialized wrapper). Facts without traps preserve the file's
 *  current trap lines. */
export const syncMarketSchemaUnlocked = async (
    coin: string,
    facts: MarketSchemaFacts,
    username: string,
): Promise<void> => {
    const folder = findFolderByName(MARKET_SCHEMA_FOLDER);
    if (!folder) return;
    const cleanCoin = (coin || '').replace(/[^A-Za-z0-9_-]/g, '') || 'GENERAL';
    const merged: MarketSchemaFacts = {
        ...facts,
        traps: facts.traps ?? existingTraps(cleanCoin),
    };
    const content = buildMarketSchemaContent(cleanCoin, merged);
    await upsertHarnessFileUnlocked(folder, `${cleanCoin}.md`, content, username);
};

/** Serialized public API — see withNotebookWriteLock. */
export const syncMarketSchema = (coin: string, facts: MarketSchemaFacts, username: string): Promise<void> =>
    withNotebookWriteLock(() => syncMarketSchemaUnlocked(coin, facts, username));

/**
 * Gather the measurable facts, best-effort. Every reader is cached inside
 * MarketDataService; a blocked network costs the measured half and the
 * schema carries the labelled conventions instead. Never throws.
 */
export const collectMarketSchemaFacts = async (coin: string): Promise<MarketSchemaFacts> => {
    const facts: MarketSchemaFacts = {};
    try {
        const units = await fetchSymbolUnits(coin);
        if (units) {
            facts.tickSize = units.tickSize;
            facts.stepSize = units.stepSize;
            facts.baseAsset = units.baseAsset;
            facts.quoteAsset = units.quoteAsset;
        }
    } catch { /* unverified units */ }
    try {
        const hist = await fetchFundingRateHistory(coin, 8);
        if (hist.length >= 3) {
            // The settlement spacing IS the schedule: consecutive funding
            // timestamps, mode delta in hours. A 4h coin reads 4h, not the
            // 8h convention.
            const deltas: number[] = [];
            for (let i = 1; i < hist.length; i += 1) {
                const d = (hist[i].t - hist[i - 1].t) / 3600_000;
                if (d > 0 && d <= 24) deltas.push(Math.round(d * 10) / 10);
            }
            if (deltas.length >= 2) {
                const counts = new Map<number, number>();
                for (const d of deltas) counts.set(d, (counts.get(d) ?? 0) + 1);
                const mode = [...counts.entries()].sort((a, b) => b[1] - a[1])[0][0];
                facts.fundingIntervalHours = mode;
                facts.fundingMeasured = true;
            }
        }
    } catch { /* convention fallback */ }
    try {
        const mark = await fetchMarkIndex(coin);
        if (mark.available && mark.nextFundingTime > 0) {
            const d = new Date(mark.nextFundingTime);
            facts.nextFundingUtc = `${String(d.getUTCHours()).padStart(2, '0')}:${String(d.getUTCMinutes()).padStart(2, '0')} UTC`;
        }
    } catch { /* no next-funding line */ }
    return facts;
};

/** Regime words that mean "the tape was ranging/compressed at entry" — the
 *  entry-knowable half of a regime trap. Matches the chart's own vocabulary
 *  (regimeCore) and the legacy journal words. */
const RANGE_REGIME_WORDS = new Set(['range', 'ranging', 'compressed', 'compression', 'neutral']);

/**
 * Learned traps from the coin's REAL journal rows (pure, contract-pinned).
 * A simulated paper fill is excluded outright: its lessons are about the
 * fill model, not the market, and must never write a real-market trap.
 *
 * Two kinds, both knowable at entry:
 *  - stop-swept: the stop was touched and price still reached the target —
 *    it sat inside the setup's noise (resolutionRecord.slHitThenReversedToTp).
 *  - range-noise: a loss entered in a ranging/compressed regime whose adverse
 *    excursion reached ≥0.9R — the stop sat inside range noise the regime
 *    read already named (resolutionRecord.regimeAtEntry + maeR).
 */
export const learnedSchemaTraps = (coin: string, trades: LoggedTrade[]): SchemaTrap[] => {
    const base = baseOf(coin || '');
    if (!base) return [];
    const real = (trades ?? []).filter(t =>
        t.simulated !== true
        && t.outcome === TradeOutcome.LOSS
        && typeof t.analysis?.coinName === 'string'
        && baseOf(t.analysis.coinName) === base);
    let swept = 0;
    let rangeNoise = 0;
    for (const t of real) {
        const r = t.resolutionRecord;
        if (!r) continue;
        if (r.slHitThenReversedToTp === true) swept += 1;
        const regime = (r.regimeAtEntry ?? '').toLowerCase().trim();
        if (RANGE_REGIME_WORDS.has(regime) && typeof r.maeR === 'number' && r.maeR >= 0.9) rangeNoise += 1;
    }
    const out: SchemaTrap[] = [];
    if (swept >= SCHEMA_TRAP_MIN_COUNT) {
        out.push({ line: 'stop swept before the target — it sat inside the setup\'s noise; give room beyond the swept liquidity', count: swept });
    }
    if (rangeNoise >= SCHEMA_TRAP_MIN_COUNT) {
        out.push({ line: 'losses entered in range/compression with ≥0.9R adverse excursion — the regime read named the noise the stop sat in', count: rangeNoise });
    }
    return out.slice(0, SCHEMA_TRAP_MAX_LINES);
};